KEEP = {"legend.png"}   # still correct: MAIN palette unchanged


def md5(p):
    return hashlib.md5(p.read_bytes()).hexdigest()


def main():
    check = "--check" in sys.argv
    missing = [s for s in MAP.values() if not (SRC / s).exists()]
    if missing:
        sys.exit(f"MISSING SOURCES:\n  " + "\n  ".join(missing))

    copied = stale = 0
    for tgt, src in sorted(MAP.items()):
        sp, tp = SRC / src, DST / tgt
        same = tp.exists() and md5(sp) == md5(tp)
        if same:
            continue
        stale += 1
        if not check:
            shutil.copy2(sp, tp)
            copied += 1
        print(f"{'WOULD COPY' if check else 'copied':<11} {src:<32} -> {tgt}")

    # audit: every figure the document references must now match its source
    print(f"\n{len(MAP)} mapped | {stale} differed | {copied} copied")
    bad = [t for t, s in MAP.items() if md5(SRC / s) != md5(DST / t)] if not check else []
    print("VERIFY:", "all targets match their source" if not bad else f"MISMATCH {bad}")
    print("kept as-is (no fitted values / palette unchanged):", ", ".join(sorted(KEEP)))


if __name__ == "__main__":
    main()
